/** 模式指示符。 */
export const MODE_BYTE = 0b0100;

/**
 * 字节模式下的字符计数指示符位数。
 * 版本 1–9 为 8 位，版本 10–40 为 16 位。
 */
export function byteModeCharCountBits(version: number): number {
  return version <= 9 ? 8 : 16;
}

/** 版本 1..40 的合法范围。 */
export const MIN_VERSION = 1;
